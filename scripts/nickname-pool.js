// 用「别名 + 中文序数」兜底，仍保持真实形态、无数字/拉丁尾巴。
const CN_ORD = ["二", "三", "四", "五", "六", "七", "八", "九", "十"];
function cloneNickname(base, round) {
  const list = CLONE_ALIASES[base];
  if (!list || !list.length) return base;
  if (round >= 1 && round <= list.length) return list[round - 1];
  const reuse = list[(Math.max(1, round) - 1) % list.length];
  const ord = CN_ORD[Math.min(round - list.length - 1, CN_ORD.length - 1)] || "再";
  return `${reuse}${ord}号`;
}

