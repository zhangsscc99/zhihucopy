// 通用池确定性取名：从 start 起环形扫描，返回第一个未被占用的名字。
// taken 是已用昵称集合（含库内现名与本批已分配名）；池子耗尽时抛错而非硬凑。
function genericNickname(start, taken) {
  for (let k = 0; k < GENERIC_POOL.length; k++) {
    const name = GENERIC_POOL[(start + k) % GENERIC_POOL.length];
    if (!taken.has(name)) return name;
  }
  throw new Error(
    `nickname-pool: GENERIC_POOL 已耗尽（${GENERIC_POOL.length} 个全被占用），请扩充池子`
  );
}

// ---- 加载即校验：形态 + 唯一性 ---------------------------------------------
{
  const all = [];
  for (const [base, list] of Object.entries(CLONE_ALIASES)) {
    if (isSuspiciousNickname(base)) {
      throw new Error(`nickname-pool: 原型名「${base}」本身是可疑形态`);
    }
    all.push(...list);
  }
  all.push(...GENERIC_POOL);
  const seen = new Set();
  for (const n of all) {
    const len = [...String(n)].length;
    if (len < 2 || len > 6) {
      throw new Error(`nickname-pool: 「${n}」长度 ${len} 超出 2–6 字`);
    }
    if (/[0-9A-Za-z]/.test(n)) {
      throw new Error(`nickname-pool: 「${n}」含数字/拉丁字符`);
    }
    if (isSuspiciousNickname(n)) {
      throw new Error(`nickname-pool: 「${n}」命中可疑形态`);
    }
    if (seen.has(n)) throw new Error(`nickname-pool: 「${n}」重名`);
    seen.add(n);
  }
  // 别名不得与任一原型重名（否则 persona 映射歧义）。
  const bases = new Set(Object.keys(CLONE_ALIASES));
  for (const n of all) {
    if (bases.has(n)) throw new Error(`nickname-pool: 别名「${n}」与种子原型重名`);
  }
}

