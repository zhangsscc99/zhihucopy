const cnLen = (s) => [...String(s || "")].length;

// 锚定命中：cat 领域内、关键词命中回答正文的文案数组（kw 命中优先，
// 空 kw 的本类兜底句排在命中集之后由调用方决定要不要并入）。
function anchoredTexts(cat, content, { includeFallback = true } = {}) {
  const pool = DOMAIN_COMMENTS[cat] || [];
  const body = String(content || "");
  const hit = [];
  const rest = [];
  for (const e of pool) {
    if (e.k.length && e.k.some((kw) => body.includes(kw))) hit.push(e.t);
    else rest.push(e.t);
  }
  return includeFallback ? hit.concat(rest) : hit;
}

// 二级回复取句：k 命中父评论文本（anchorText，一般传父评论正文；缺省时
// 回落到回答正文）的排前面，k=[] 兜底句排后面。返回 {matched, fallback}
// 两个文案数组，调用方决定优先级。
function replyTexts(anchorText = "") {
  const body = String(anchorText || "");
  const matched = [];
  const fallback = [];
  for (const e of REPLIES) {
    if (e.k.length === 0) fallback.push(e.t);
    else if (e.k.some((kw) => body.includes(kw))) matched.push(e.t);
  }
  return { matched, fallback };
}

// 修正脚本的确定性取句：候选顺序 = 锚定命中 → 本类兜底 → 通用池 → 回复池
// （白名单句式一律剔除）。shift 让同一批命中在不同 answer 间错开取句，
// 避免重写后又形成新的高频句；同一 DB 状态下结果恒定（幂等）。
// opts.allow(t)：额外的全站约束（占用/跨题上限），返回 false 即跳过该句；
// opts.prefer(t)：同层内的优先谓词（如「已计费到本题」），命中的排前面；
// opts.parentText：被重写评论的父评论正文，用于回复句 k 匹配；
// opts.onlyAnchored=true 时只看第一层 k 命中句（不含 k=[] 兜底与后面两层）。
// 全占满返回 null。
function pickReplacement(cat, content, used, shift = 0, opts = {}) {
  const { allow, prefer, parentText, onlyAnchored = false } = opts;
  const replies = replyTexts(parentText || content);
  const tiers = onlyAnchored
    ? [anchoredTexts(cat, content, { includeFallback: false })]
    : [
        anchoredTexts(cat, content),
        GENERIC_COMMENTS.filter((t) => !WHITELIST_SET.has(t)),
        replies.matched.concat(replies.fallback).filter((t) => !WHITELIST_SET.has(t)),
      ];
  for (const arr of tiers) {
    if (!arr.length) continue;
    const cands = [];
    for (let i = 0; i < arr.length; i++) {
      const t = arr[(shift + i) % arr.length];
      if (!used.has(t) && (!allow || allow(t))) cands.push(t);
    }
    if (!cands.length) continue;
    const pref = prefer ? cands.filter(prefer) : cands;
    return pref.length ? pref[0] : cands[0];
  }
  return null;
}

