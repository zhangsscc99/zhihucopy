const cnLen = (s) => [...String(s || "")].length;

// 锚定命中：cat 领域内、关键词命中回答正文的文案数组（kw 命中优先，
// 空 kw 的本类兜底句排在命中集之后由调用方决定要不要并入）。
function anchoredTexts(cat, content, { includeFallback = true } = {}) {
  const pool = DOMAIN_COMMENTS[cat] || [];
  const body = String(content || "");
  const hit = [];
  const rest = [];
  for (const e of pool) {
    if (e.k.length && e.k.some((kw) => body.includes(kw))) hit.push(e.t);
    else rest.push(e.t);
  }
  return includeFallback ? hit.concat(rest) : hit;
}

// 修正脚本的确定性取句：候选顺序 = 锚定命中 → 本类兜底 → 通用池 → 回复池
// （白名单句式一律剔除）。shift 让同一批命中在不同 answer 间错开取句，
// 避免重写后又形成新的高频句；同一 DB 状态下结果恒定（幂等）。
// 全占满返回 null。
function pickReplacement(cat, content, used, shift = 0) {
  const tiers = [
    anchoredTexts(cat, content),
    GENERIC_COMMENTS.filter((t) => !WHITELIST_SET.has(t)),
    REPLIES.filter((t) => !WHITELIST_SET.has(t)),
  ];
  for (const arr of tiers) {
    if (!arr.length) continue;
    for (let i = 0; i < arr.length; i++) {
      const t = arr[(shift + i) % arr.length];
      if (!used.has(t)) return t;
    }
  }
  return null;
}

// 语料自检：结构、长度、白名单交叉（seed.js 加载时执行）。
function validate() {
  const problems = [];
  const allTexts = [];
  for (const [cat, pool] of Object.entries(DOMAIN_COMMENTS)) {
    for (const e of pool) {
      if (!Array.isArray(e.k)) problems.push(`${cat}: k 非数组`);
      if (cnLen(e.t) < 8) problems.push(`${cat}: 锚定评论过短「${e.t}」`);
      allTexts.push(e.t);
    }
  }
  for (const t of GENERIC_COMMENTS) {
    if (cnLen(t) < 8) problems.push(`通用评论过短「${t}」`);
    allTexts.push(t);
  }
  for (const t of REPLIES) {
    if (cnLen(t) < 6) problems.push(`回复过短「${t}」`);
    allTexts.push(t);
  }
  const dup = allTexts.filter((t, i) => allTexts.indexOf(t) !== i);
  if (dup.length) problems.push(`池内重复句: ${[...new Set(dup)].join(" | ")}`);
  const wl = allTexts.filter((t) => WHITELIST_SET.has(t));
  if (wl.length) problems.push(`语料仍含白名单句: ${wl.join(" | ")}`);
  return problems;
}

