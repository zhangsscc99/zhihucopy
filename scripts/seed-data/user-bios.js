const DOMAINS = Object.keys(DOMAIN_BIOS);

function domainOf(domains) {
  const list = Array.isArray(domains) ? domains : [domains];
  for (const d of list) if (DOMAIN_BIOS[d]) return d;
  return "work";
}

// 把补语接到句尾：原句已带句末标点时不要多造一个逗号。
function withFiller(sentence, filler) {
  const s = String(sentence).trim();
  if (/[。！？…”」]$/.test(s)) return `${s.replace(/[。]$/, "。")}${filler}。`;
  return `${s}，${filler}。`;
}

/**
 * round 从 1 起；同 domain 内不同 round 必得不同 bio。
 * 候选序列 = 领域池本身（12 条）→ 池 × 补语（12×12 条），共 156 条，够覆盖
 * 「同一领域 3 个原型 × 7 个 clone」的规模。
 */
function cloneBio(domains, round) {
  const d = domainOf(domains);
  const pool = DOMAIN_BIOS[d];
  const n = Math.max(1, Number(round) || 1);
  if (n <= pool.length) return pool[n - 1];
  const k = n - pool.length - 1;
  const sentence = pool[k % pool.length];
  const filler = FILLERS[Math.floor(k / pool.length) % FILLERS.length];
  return withFiller(sentence, filler);
}

// 简介首句（到第一个「。」）：Z1161 用「首句」判重，池内 200 句首句两两不同。
function headOf(bio) {
  return String(bio || "").trim().split("。")[0];
}

module.exports = { DOMAIN_BIOS, FILLERS, DOMAINS, cloneBio, domainOf, headOf, withFiller };
