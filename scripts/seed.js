const truncateSentence = (s, max) => {
  if (cnLen(s) <= max) return s;
  const chars = [...s];
  let cut = -1;
  for (let i = Math.min(chars.length, max) - 1; i > 40; i--) {
    if ("。！？".includes(chars[i])) {
      cut = i + 1;
      break;
    }
    if (chars[i] === "\n" && cut === -1 && i > 120) cut = i;
  }
  return cut > 0 ? chars.slice(0, cut).join("") : chars.slice(0, max).join("");
};

