function makeAnswer(cat, opts) {
  const { qSeed, k, hook, blockOrder } = opts;
  const C = CORPUS[cat];
  const r = rngFor(qSeed + k * 101 + 7);
  const parts = [];
  if (hook) parts.push(hook);

  // 开场与收尾按 k 错开，保证同一个问题下的三条回答不撞句
  parts.push(C.openers[(qSeed + k) % C.openers.length]);

  // 素材块：把该大类的块按问题打乱后平均分给三条回答，互不重叠
  const nBlocks = blockOrder.length;
  const per = Math.max(2, Math.floor(nBlocks / 3));
  const start = (k * (per + 1)) % nBlocks;
  const mine = [];
  for (let i = 0; i < per; i++) mine.push(blockOrder[(start + i) % nBlocks]);

  parts.push(mine[0]);
  parts.push(mine[1]);
  let bi = 2;
  if (r() < 0.6 && C.formats && C.formats.length) parts.push(pickR(r, C.formats));
  if (cnLen(parts.join("\n\n")) < 340 && bi < mine.length) parts.push(mine[bi++]);

  let s = parts.join("\n\n");
  // 目标 450–650 字：不足就继续补素材块，超过 800 再裁
  while (cnLen(s) < 430 && bi < mine.length) s += "\n\n" + mine[bi++];

  s += "\n\n" + C.closers[(qSeed + k) % C.closers.length];

  // 太长先丢掉格式块，再丢中间段，最后按句号截断
  if (cnLen(s) > 800) {
    const segs = s.split("\n\n");
    const idx = segs.findIndex((x) => x.startsWith("```") || x.startsWith("- ") || x.startsWith("> "));
    if (idx > 2) s = segs.filter((_, i) => i !== idx).join("\n\n");
  }
  if (cnLen(s) > 800) {
    const segs = s.split("\n\n");
    // 保留 hook/开场/收尾，优先删中段的正文块
    if (segs.length > 4) s = segs.filter((_, i) => i !== segs.length - 2).join("\n\n");
  }
  if (cnLen(s) > 800) s = truncateSentence(s, 780);
  while (cnLen(s) < 200) s += "\n\n" + (mine[bi++ % mine.length] || "");
  if (cnLen(s) > 800) s = truncateSentence(s, 780);
  return s;
}

function makeDetail(cat, seed, padList) {
  const D = CORPUS[cat].detail;
  const r = rngFor(seed);
  let s = [pickR(r, D.s), pickR(r, D.a), pickR(r, D.q)].join("\n\n");
  let guard = 0;
  while (cnLen(s) < 250 && guard++ < 3) s += "\n\n" + pickR(r, padList);
  if (cnLen(s) > 400) s = truncateSentence(s, 395);
  return s;
}

